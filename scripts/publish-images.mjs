#!/usr/bin/env node
// Upload the JPEGs from scripts/build-images.mjs to R2 and point the site at them.
//
//   node scripts/publish-images.mjs [--dry-run]
//
// 1. Uploads every file in image-build/img/ to the R2 bucket behind
//    cdn.isthishenry.com via wrangler (which must be logged in), with a one-year
//    immutable Cache-Control: the filenames carry a content hash.
//    image-build/uploaded.json records progress, so a rerun resumes.
// 2. Checks every URL serves the uploaded bytes.
// 3. Writes src/data/imageVariants.js: each image's widths and pixel size, which
//    the site uses for srcset, the blur preview and reserving layout space.
// 4. Swaps the site's image URLs for the largest new JPEG, and restores the files
//    if navigation.js still resolves any PNG/JPEG to an original.

import { execFile } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';
import { CDN_ORIGIN, navigationUrls, restore, rewriteSourceUrls } from './lib/source-urls.mjs';

const BUCKET = 'isthishenry';
const CACHE_CONTROL = 'public, max-age=31536000, immutable';
const CONCURRENCY = 6;
const MAX_ATTEMPTS = 3;

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const BUILD_DIR = path.join(ROOT, 'image-build');
const VARIANTS_FILE = path.join(ROOT, 'src/data/imageVariants.js');
const dryRun = process.argv.includes('--dry-run');
const run = promisify(execFile);

const { images } = JSON.parse(await readFile(path.join(BUILD_DIR, 'manifest.json'), 'utf8'));
const files = images.flatMap((image) => image.files);

async function pool(items, worker) {
  let next = 0;
  await Promise.all(
    Array.from({ length: CONCURRENCY }, async () => {
      while (next < items.length) await worker(items[next++]);
    }),
  );
}

// ---------------------------------------------------------------------------
// 1. Upload
// ---------------------------------------------------------------------------

const statePath = path.join(BUILD_DIR, 'uploaded.json');
const uploaded = new Set(JSON.parse(await readFile(statePath, 'utf8').catch(() => '[]')));
const pending = files.filter((file) => !uploaded.has(file.key));
console.log(`${files.length} files, ${pending.length} to upload to ${BUCKET}`);

if (!dryRun && pending.length) {
  let saving = Promise.resolve();
  const save = () => (saving = saving.then(() => writeFile(statePath, JSON.stringify([...uploaded]))));
  const failed = [];
  let done = 0;
  await pool(pending, async (file) => {
    let error = null;
    for (let attempt = 1; attempt <= MAX_ATTEMPTS; attempt++) {
      try {
        await run('npx', [
          '--no-install', 'wrangler', 'r2', 'object', 'put', `${BUCKET}/${file.key}`,
          '--file', path.join(BUILD_DIR, file.key),
          '--content-type', 'image/jpeg',
          '--cache-control', CACHE_CONTROL,
          '--remote',
        ], { cwd: ROOT });
        error = null;
        break;
      } catch (err) {
        error = err;
      }
    }
    if (error) failed.push(`${file.key}: ${String(error.stderr || error.message).trim().split('\n').pop()}`);
    else {
      uploaded.add(file.key);
      await save();
    }
    if (++done % 25 === 0 || done === pending.length) console.log(`  ${done}/${pending.length}`);
  });
  if (failed.length) {
    console.error(`${failed.length} uploads failed — rerun to retry:\n  ${failed.join('\n  ')}`);
    process.exit(1);
  }
}

// ---------------------------------------------------------------------------
// 2. Every URL must serve the uploaded file
// ---------------------------------------------------------------------------

if (!dryRun) {
  const broken = [];
  await pool(files, async (file) => {
    const res = await fetch(`${CDN_ORIGIN}/${file.key}`, { method: 'HEAD' }).catch((err) => ({ ok: false, status: err.message }));
    const length = res.ok ? Number(res.headers.get('content-length')) : null;
    if (!res.ok || length !== file.bytes) broken.push(`${file.key}: ${res.ok ? `${length} bytes, expected ${file.bytes}` : res.status}`);
  });
  if (broken.length) {
    console.error(`${broken.length} URLs not serving the uploaded file:\n  ${broken.join('\n  ')}`);
    process.exit(1);
  }
  console.log(`All ${files.length} URLs serve the uploaded files`);
}

// ---------------------------------------------------------------------------
// 3. Size data for the site
// ---------------------------------------------------------------------------

const variants = images
  .map((image) => `  ${JSON.stringify(`${CDN_ORIGIN}/${image.top}`)}: { w: ${image.width}, h: ${image.height}, widths: [${image.widths.join(', ')}] },`)
  .join('\n');
const variantsSource = `// Generated by scripts/publish-images.mjs. Do not edit by hand.
// Keyed by each image's largest JPEG. The other widths share its URL with
// -<width>.jpg, and -blur.jpg is a tiny preview. w/h: the largest one's pixels.
export const imageVariants = {
${variants}
};
`;
if (!dryRun) await writeFile(VARIANTS_FILE, variantsSource);

// ---------------------------------------------------------------------------
// 4. Point the site at the new JPEGs
// ---------------------------------------------------------------------------

const originals = await rewriteSourceUrls(
  ROOT,
  images.map((image) => ({
    from: image.sourceUrl,
    relative: path.posix.basename(image.sourceKey),
    to: `${CDN_ORIGIN}/${image.top}`,
  })),
  { dryRun },
);
if (dryRun) process.exit(0);

const urls = await navigationUrls(ROOT);
const leftovers = urls.filter((url) => url.startsWith(CDN_ORIGIN) && /\.(png|jpe?g)$/i.test(url) && !url.startsWith(`${CDN_ORIGIN}/img/`));
if (leftovers.length) {
  await restore(originals);
  console.error(`Restored the original files — still pointing at original images:\n  ${leftovers.join('\n  ')}`);
  process.exit(1);
}
const published = new Set(urls.filter((url) => url.startsWith(`${CDN_ORIGIN}/img/`)));
console.log(`\nDone. navigation.js now uses ${published.size} re-encoded images and no original PNGs/JPEGs.`);
